"""The real arithmetic used by multiprecision test oracles.

mpmath creates its scalar classes and arithmetic methods at runtime, so source
inference cannot describe them consistently across supported mpmath versions.
This structural interface describes the operations the oracles need, without
changing mpmath's constructors, precision context or numerical implementation.
"""

from typing import Protocol


class MPReal(Protocol):
    def __float__(self) -> float: ...
    def __abs__(self) -> "MPReal": ...
    def __neg__(self) -> "MPReal": ...
    def __add__(self, other: "MPReal | int | float", /) -> "MPReal": ...
    def __radd__(self, other: "MPReal | int | float", /) -> "MPReal": ...
    def __sub__(self, other: "MPReal | int | float", /) -> "MPReal": ...
    def __rsub__(self, other: "MPReal | int | float", /) -> "MPReal": ...
    def __mul__(self, other: "MPReal | int | float", /) -> "MPReal": ...
    def __rmul__(self, other: "MPReal | int | float", /) -> "MPReal": ...
    def __truediv__(self, other: "MPReal | int | float", /) -> "MPReal": ...
    def __rtruediv__(self, other: "MPReal | int | float", /) -> "MPReal": ...
    def __pow__(self, exponent: int, /) -> "MPReal": ...
    def __lt__(self, other: "MPReal | int | float", /) -> bool: ...
    def __le__(self, other: "MPReal | int | float", /) -> bool: ...
    def __gt__(self, other: "MPReal | int | float", /) -> bool: ...
    def __ge__(self, other: "MPReal | int | float", /) -> bool: ...
